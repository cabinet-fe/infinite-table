export interface ArchPackage {
  key: ArchPackageKey
  name: string
  /** 仓库内路径 */
  dir: string
  /** 一句话定位 */
  tagline: string
  /** 这层是什么：为什么存在、在整体中扮演什么角色（叙事讲机制，不列 API） */
  role: string
  /** 详细作用：机制级清单 */
  responsibilities: string[]
  /** 典型场景：运行时什么时候会经过这层 */
  scenarios: string[]
  /** 扩展举例：想加某种能力时在这层做什么、收益是什么 */
  extensions: string[]
  /** 依赖的包（key 引用 ARCH_PACKAGES；箭头方向 = 本包 → 依赖） */
  dependsOn: ArchPackageKey[]
  /** 不做什么：这层刻意不管的事与原因 */
  boundaries: string[]
}

